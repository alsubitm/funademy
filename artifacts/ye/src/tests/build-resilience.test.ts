/**
 * Guards against publish breakage: `next build` statically renders pages,
 * and any page that queries the database at build time without a safeQuery
 * fallback will crash the build when the production DB is unreachable or
 * out of sync (this happened before task 95).
 *
 * This test runs a real `next build` with a deliberately unreachable
 * DATABASE_URL. If a future page reintroduces an unguarded build-time DB
 * query, the build — and therefore this test — fails.
 */
import { describe, it, expect } from 'vitest';
import { execFile } from 'node:child_process';
import { mkdir, readFile, rm, rmdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const YE_ROOT = path.resolve(__dirname, '..', '..');
const DIST_DIR = '.next-build-test';
const NEXT_ENV_DTS = path.join(YE_ROOT, 'next-env.d.ts');
const UNREACHABLE_DB_URL = 'postgresql://nouser:nopass@127.0.0.1:5999/nodb';
const BUILD_TIMEOUT_MS = 240_000;

/**
 * Hermetic env for the child build. When this test runs under vitest (and
 * under the validation harness's `pnpm --filter ... test`), the process env
 * is polluted with NODE_ENV=test, VITEST*, npm_* / pnpm lifecycle vars and
 * NEXT_* internals that corrupt a nested `next build` (e.g.
 * "Cannot find module for page: /_document"). Start from a whitelist
 * instead of trying to strip a blocklist.
 */
function childEnv(): NodeJS.ProcessEnv {
  const keep = ['PATH', 'HOME', 'TMPDIR', 'SHELL', 'USER', 'LANG', 'LC_ALL', 'TZ'];
  const env: Record<string, string> = {};
  for (const k of keep) {
    const v = process.env[k];
    if (v !== undefined) env[k] = v;
  }
  env.NODE_ENV = 'production';
  env.DATABASE_URL = UNREACHABLE_DB_URL;
  env.NEXT_DIST_DIR = DIST_DIR;
  env.NEXT_TELEMETRY_DISABLED = '1';
  return env as unknown as NodeJS.ProcessEnv;
}

function run(cmd: string, args: string[]): Promise<{ code: number; output: string }> {
  return new Promise((resolve) => {
    execFile(
      cmd,
      args,
      {
        cwd: YE_ROOT,
        timeout: BUILD_TIMEOUT_MS - 20_000,
        maxBuffer: 32 * 1024 * 1024,
        env: childEnv(),
      },
      (error: import('node:child_process').ExecFileException | null, stdout: string, stderr: string) => {
        resolve({
          code: error ? (typeof error.code === 'number' ? error.code : 1) : 0,
          output: `${stdout}\n${stderr}`,
        });
      },
    );
  });
}

function runBuild(): Promise<{ code: number; output: string }> {
  // Invoke the next binary directly (not `pnpm run build`) so no pnpm/npm
  // lifecycle env leaks into the child. The prisma client is already
  // generated by install/dev; regenerating here would race concurrent runs.
  return run(path.join(YE_ROOT, 'node_modules', '.bin', 'next'), ['build']);
}

const LOCK_DIR = path.join(YE_ROOT, '.build-resilience.lock');

/**
 * Cross-process mutex: the validation harness and the ye-tests workflow can
 * run this suite concurrently, and two `next build`s sharing one distDir
 * corrupt each other (MODULE_NOT_FOUND on webpack-runtime.js during export).
 */
async function acquireLock(): Promise<void> {
  const deadline = Date.now() + BUILD_TIMEOUT_MS;
  for (;;) {
    try {
      await mkdir(LOCK_DIR);
      return;
    } catch {
      if (Date.now() > deadline) {
        // Assume a stale lock from a killed run and steal it.
        await rm(LOCK_DIR, { recursive: true, force: true });
      } else {
        await new Promise((r) => setTimeout(r, 2000));
      }
    }
  }
}

/** Transient build-worker corruption, not a DB-fallback regression. */
function isInfraFlake(output: string): boolean {
  return /Cannot find module .*webpack-runtime\.js/.test(output);
}

describe('build resilience (publish must not depend on a reachable DB)', () => {
  it(
    'next build succeeds with an unreachable DATABASE_URL',
    async () => {
      const distPath = path.join(YE_ROOT, DIST_DIR);
      await acquireLock();
      try {
        let result = { code: 1, output: '' };
        for (let attempt = 1; attempt <= 2; attempt++) {
          // A stale/partial output dir from a previous aborted run can
          // corrupt the build, so always start clean.
          await rm(distPath, { recursive: true, force: true });
          result = await runBuild();
          if (result.code === 0 || !isInfraFlake(result.output)) break;
        }
        if (result.code !== 0) {
          // Surface the tail of the build log so the offending page is visible.
          const tail = result.output.split('\n').slice(-60).join('\n');
          expect.fail(
            `next build failed with an unreachable DATABASE_URL (exit ${result.code}). ` +
              `A page is likely querying the DB at build time without a safeQuery fallback.\n${tail}`,
          );
        }
        expect(result.code).toBe(0);
      } finally {
        await rm(distPath, { recursive: true, force: true });
        // The nested build rewrites the TRACKED next-env.d.ts to reference
        // this test's distDir (`.next-build-test/types/routes.d.ts`), which
        // breaks standalone typecheck on a clean checkout. Restore the
        // standard `.next` reference so test runs never leave
        // generated-file drift (idempotent — also heals drift left by a
        // previously killed run).
        const nextEnv = await readFile(NEXT_ENV_DTS, 'utf8').catch(() => null);
        if (nextEnv && nextEnv.includes(DIST_DIR)) {
          await writeFile(NEXT_ENV_DTS, nextEnv.split(`/${DIST_DIR}/`).join('/.next/'));
        }
        await rmdir(LOCK_DIR).catch(() => {});
      }
    },
    BUILD_TIMEOUT_MS * 2 + 60_000,
  );
});
